'''
Run the standard bot-tuning experiments and write a Markdown report.

    python -m sim.experiments                 # full run (~6 min on 4 cores)
    python -m sim.experiments --scale 0.1     # quick smoke run

Experiments:
  1. Heads-up: TAG baseline vs ExploitBot against every zoo bot, on identical
     duplicate deals, so the exploit edge is a paired difference.
  2. Learning curve: how the exploit edge grows as the bot gathers stats.
  3. 6-max tables (scared table, mixed table) with each hero.
  4. Observed stats per bot, and how many hands each stat needs to be reliable.
'''
import argparse
import os
import time
from multiprocessing import Pool

from .match import run_match, paired_diff
from .stats import STAT_INFO

VILLAINS = ['Terrified', 'Scared', 'Nervous', 'Nit', 'Station', 'Maniac', 'LAG', 'TAG']
HEROES = ['TAG', 'Exploit']
TABLES = {
    'Scared table': ['Nervous', 'Scared', 'Terrified', 'Nit', 'TAG'],
    'Mixed table': ['Nervous', 'Scared', 'Station', 'Maniac', 'LAG'],
}
CURVE = [(0, 100), (100, 500), (500, 2500), (2500, None)]   # in deals
STAT_KEYS = ['vpip', 'pfr', 'three_bet', 'steal', 'fold_steal', 'cbet', 'fold_cbet',
             'fvb', 'afq', 'wtsd', 'wsd']


def _hu_job(args):
    hero, villain, deals, seed = args
    res = run_match([(hero, 'Hero'), (villain, 'Villain')], deals, seed=seed)
    return ('hu', hero, villain), res.blocks['Hero'], None


def _table_job(args):
    hero, table, deals, seed = args
    lineup = [(hero, 'Hero')] + [(k, k) for k in TABLES[table]]
    res = run_match(lineup, deals, seed=seed)
    return ('table', hero, table), res.blocks, res.observer


def _fmt(x, ci):
    return '%+.1f ± %.1f' % (x, ci)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--scale', type=float, default=1.0, help='multiply all hand counts')
    ap.add_argument('--out', default=os.path.join(os.path.dirname(__file__), 'RESULTS.md'))
    ap.add_argument('--procs', type=int, default=os.cpu_count())
    a = ap.parse_args(argv)

    hu_deals = int(100_000 * a.scale)
    table_deals = int(30_000 * a.scale)
    jobs = []
    for i, v in enumerate(VILLAINS):
        deals = hu_deals * (3 if v == 'Maniac' else 1)   # maniac pots are very high variance
        for hero in HEROES:
            jobs.append((_hu_job, (hero, v, deals, 100 + i)))
    for i, t in enumerate(TABLES):
        for hero in HEROES:
            jobs.append((_table_job, (hero, t, table_deals, 200 + i)))

    t0 = time.time()
    with Pool(a.procs) as pool:
        outs = pool.map(_dispatch, jobs, chunksize=1)
    elapsed = time.time() - t0
    res = {key: (blocks, obs) for key, blocks, obs in outs}

    lines = ['# Bot tuning results', '',
             'Generated by `python -m sim.experiments%s` in %.0fs. All win rates are in **bb/100** '
             '(big blinds won per 100 hands) with **95%% confidence intervals**. Duplicate dealing '
             '(every deal replayed with seats rotated) and all-in EV are used to cut variance; '
             '"edge" is a paired difference on identical deals.' % (
                 '' if a.scale == 1 else ' --scale %g' % a.scale, elapsed), '']

    # 1. heads-up
    lines += ['## 1. Heads-up: baseline vs exploit', '',
              '| Villain | Hands | TAG baseline | ExploitBot | Edge from opponent modeling |',
              '|---|---:|---:|---:|---:|']
    hu_edges = {}
    for v in VILLAINS:
        base = res[('hu', 'TAG', v)][0]
        expl = res[('hu', 'Exploit', v)][0]
        d, ci = paired_diff(expl, base)
        hu_edges[v] = (d, ci)
        lines.append('| %s | %s | %s | %s | **%s** |' % (
            v, '{:,}'.format(2 * len(base)), _fmt(*_rate(base)), _fmt(*_rate(expl)), _fmt(d, ci)))
    lines += ['']

    # 2. learning curve
    lines += ['## 2. Learning curve (heads-up edge by hands played)', '',
              'Edge of ExploitBot over the TAG baseline within each window of the match.', '',
              '| Villain | ' + ' | '.join(_window(lo, hi) for lo, hi in CURVE) + ' |',
              '|---|' + '---:|' * len(CURVE)]
    for v in VILLAINS:
        base = res[('hu', 'TAG', v)][0]
        expl = res[('hu', 'Exploit', v)][0]
        cells = [_fmt(*paired_diff(expl, base, lo, hi)) if len(base[lo:hi]) > 1 else '-'
                 for lo, hi in CURVE]
        lines.append('| %s | %s |' % (v, ' | '.join(cells)))
    lines += ['']

    # 3. six-max tables
    lines += ['## 3. Six-max tables', '']
    for t in TABLES:
        base_blocks, base_obs = res[('table', 'TAG', t)]
        expl_blocks, expl_obs = res[('table', 'Exploit', t)]
        d, ci = paired_diff(expl_blocks['Hero'], base_blocks['Hero'])
        n_hands = 6 * len(base_blocks['Hero'])
        lines += ['### %s (%s hands per hero)' % (t, '{:,}'.format(n_hands)), '',
                  '| Player | With TAG hero | With ExploitBot hero |', '|---|---:|---:|']
        for name in ['Hero'] + TABLES[t]:
            lines.append('| %s | %s | %s |' % (
                name, _fmt(*_rate(base_blocks[name])), _fmt(*_rate(expl_blocks[name]))))
        lines += ['', '**ExploitBot edge over baseline at this table: %s bb/100**' % _fmt(d, ci), '']

    # 4. stats
    obs = res[('table', 'TAG', 'Mixed table')][1]
    obs2 = res[('table', 'TAG', 'Scared table')][1]
    lines += ['## 4. Observed tendencies (raw %, six-max, TAG hero tables)', '',
              '| Player | Hands | ' + ' | '.join(STAT_INFO[k][0] for k in STAT_KEYS) + ' | AF |',
              '|---|---:|' + '---:|' * (len(STAT_KEYS) + 1)]
    rows = [('TAG (hero)', obs2.get('Hero'))] + [(n, obs2.get(n)) for n in TABLES['Scared table'] if n != 'TAG']
    rows += [(n, obs.get(n)) for n in ['Station', 'Maniac', 'LAG']]
    for label, p in rows:
        cells = []
        for k in STAT_KEYS:
            r = p.rate(k, shrink=False)
            cells.append('-' if r != r else '%.0f' % (100 * r))
        lines.append('| %s | %s | %s | %.2f |' % (label, '{:,}'.format(p.hands), ' | '.join(cells), p.af()))
    lines += ['', 'Stat definitions: ' + '; '.join(
        '**%s** %s' % (STAT_INFO[k][0], STAT_INFO[k][2]) for k in STAT_KEYS) + '.', '']

    # sample size needed
    p = obs2.get('Scared')
    lines += ['### Hands needed before a stat is reliable', '',
              'Hands needed for a ±5 percentage-point 95% interval, using how often the '
              'situation came up for the Scared bot at a six-max table.', '',
              '| Stat | Chances per 100 hands | Hands for ±5pp | Hands for ±10pp |', '|---|---:|---:|---:|']
    for k in STAT_KEYS:
        st = p.stats[k]
        if not st.opp:
            continue
        per_hand = st.opp / p.hands
        q = st.count / st.opp
        q = min(max(q, 0.05), 0.95)
        n5 = q * (1 - q) * (1.96 / 0.05) ** 2 / per_hand
        n10 = q * (1 - q) * (1.96 / 0.10) ** 2 / per_hand
        lines.append('| %s | %.1f | %s | %s |' % (STAT_INFO[k][0], 100 * per_hand,
                                                 '{:,}'.format(int(round(n5, -1))),
                                                 '{:,}'.format(int(round(n10, -1)))))
    lines += ['']

    report = '\n'.join(lines)
    with open(a.out, 'w') as f:
        f.write(report)
    print(report)


def _dispatch(job):
    fn, args = job
    return fn(args)


def _rate(blocks):
    from .match import _se
    return 100 * sum(blocks) / len(blocks), 1.96 * 100 * _se(blocks)


def _window(lo, hi):
    lo_h, hi_h = 2 * lo, (2 * hi if hi else None)
    return 'hands %s–%s' % ('{:,}'.format(lo_h), '{:,}'.format(hi_h) if hi_h else 'end')


if __name__ == '__main__':
    main()
